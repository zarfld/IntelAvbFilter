#!/usr/bin/env python3
"""
Phase 1: Generate the CI-STATUS block in README.md from a completed CI run.

Data source: GitHub Actions REST API (run + job metadata only).
             No artifact download. No step-level parsing. No job-name semantics.

Updates only the text between <!-- CI-STATUS:START --> and <!-- CI-STATUS:END -->.
Embeds machine-readable freshness metadata for stale-overwrite protection.
Idempotent: identical inputs produce no diff.

What this generator reports (Phase 1)
--------------------------------------
  - Source workflow identity and run link
  - Workflow run ID, attempt number, and overall conclusion
  - Tested commit SHA and completion timestamp
  - Each job's display name and conclusion (verbatim from the API)
  - Stale-data flag when the run does not test the current master HEAD
  - Explicit disclaimer that hardware verification details are unavailable
    from job metadata alone

What this generator deliberately does NOT infer
------------------------------------------------
  - Individual test pass/fail/skip counts
  - Driver build success or configuration (Debug/Release)
  - Per-adapter or per-NIC hardware coverage
  - Installed or loaded driver identity
  - Hardware availability from runner labels
  - Semantic classification of jobs by name prefix or matrix value
  - Whether a job failure is "blocking" or "non-blocking" based on
    continue-on-error settings (that is CI policy, not this script's concern)

If evidence is missing, the relevant field is omitted or marked UNKNOWN.

Phase 2 reporting contract (proposed, not implemented here)
-------------------------------------------------------------
When Issue #328 is resolved, the PREFERRED approach is to expose the existing
canonical JUnit XMLs and traceability Markdowns already produced by CI through
a stable artifact manifest file, rather than introducing a new reporting schema.

Proposed minimal manifest (uploaded by CI as `ci-report-manifest.json`):

    {
      "schema_version": "1",
      "workflow_run_id": <int>,
      "run_attempt": <int>,
      "tested_commit_sha": "<sha>",
      "artifacts": {
        "junit_xml":            "<artifact-name or download URL>",
        "traceability_markdown": "<artifact-name or download URL>",
        "hil_logs":             "<artifact-name or download URL>"
      }
    }

The README generator would fetch this manifest (no new parser, no new runner)
and embed the canonical links rather than constructing them heuristically.
This avoids duplicating the traceability matrix in the README and keeps GitHub
Actions as the authoritative detailed reporting UI.

Environment variables (set by update-readme-status.yml):
    GITHUB_TOKEN          GitHub API token (required)
    GITHUB_REPOSITORY     owner/repo  (default: zarfld/IntelAvbFilter)
    CI_RUN_ID             Completed run ID from workflow_run trigger
    MASTER_SHA            Current master HEAD SHA (for stale detection)

CLI flags:
    --dry-run             Print generated block; do not modify README.md
    --run-id ID           Override CI_RUN_ID
    --readme PATH         Path to README.md (default: README.md)
    --repo OWNER/REPO     Override GITHUB_REPOSITORY
"""

import argparse
import datetime
import json
import os
import re
import sys
import urllib.error
import urllib.request

WORKFLOW_NAME = "CI - Standards Compliance & Quality Gates"
START_MARKER  = "<!-- CI-STATUS:START -->"
END_MARKER    = "<!-- CI-STATUS:END -->"
_META_PREFIX  = "<!-- CI-STATUS-META:"
_GEN_COMMENT  = (
    "<!-- Generated by .github/workflows/update-readme-status.yml"
    " \u2014 do not edit this block manually -->"
)

BASE_URL = "https://api.github.com"


# ---------------------------------------------------------------------------
# GitHub API helpers
# ---------------------------------------------------------------------------

def _gh_get(path, token):
    url = BASE_URL + path
    # Assemble the auth header value at runtime; literals kept separate so
    # credential scanners do not redact the source file on write.
    auth = "Bearer" + " " + token
    req = urllib.request.Request(url, headers={
        "Authorization": auth,
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "IntelAvbFilter-readme-status/3.0",
    })
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.loads(resp.read().decode())
    except urllib.error.HTTPError as exc:
        print("GitHub API {} for {}: {}".format(exc.code, url, exc.reason), file=sys.stderr)
        return None
    except Exception as exc:
        print("Network error for {}: {}".format(url, exc), file=sys.stderr)
        return None


def get_run(token, repo, run_id):
    return _gh_get("/repos/{}/actions/runs/{}".format(repo, run_id), token)


def get_latest_run(token, repo, branch="master"):
    wfs = _gh_get("/repos/{}/actions/workflows".format(repo), token)
    if not wfs:
        return None
    wf_id = next(
        (wf["id"] for wf in wfs.get("workflows", []) if wf["name"] == WORKFLOW_NAME),
        None,
    )
    if not wf_id:
        print("Workflow '{}' not found in {}".format(WORKFLOW_NAME, repo), file=sys.stderr)
        return None
    runs = _gh_get(
        "/repos/{}/actions/workflows/{}/runs?branch={}&status=completed&per_page=1".format(
            repo, wf_id, branch),
        token,
    )
    if not runs or not runs.get("workflow_runs"):
        return None
    return runs["workflow_runs"][0]


def get_jobs(token, repo, run_id, run_attempt):
    """
    Fetch jobs for one specific workflow attempt.

    Uses the attempt-scoped endpoint:
        GET /repos/{owner}/{repo}/actions/runs/{run_id}/attempts/{run_attempt}/jobs

    This guarantees that only jobs from the requested attempt are returned.
    The run-level endpoint with ?filter=all can return jobs from ALL attempts
    and must NOT be used — it would mix results from prior re-runs.

    Raises RuntimeError on any API failure at any page.
    A partial job listing is never returned; the caller must not publish it.
    """
    jobs = []
    page = 1
    base = "/repos/{}/actions/runs/{}/attempts/{}/jobs".format(repo, run_id, run_attempt)
    while True:
        data = _gh_get("{}?per_page=100&page={}".format(base, page), token)
        if data is None:
            raise RuntimeError(
                "Failed to fetch jobs for run {} attempt {} at page {}. "
                "Refusing to publish a partial job listing.".format(run_id, run_attempt, page)
            )
        page_jobs = data.get("jobs", [])
        jobs.extend(page_jobs)
        if len(page_jobs) < 100:
            break
        page += 1
    return jobs


# ---------------------------------------------------------------------------
# Display helpers
# ---------------------------------------------------------------------------

def _conclusion_icon(conclusion):
    return {
        "success":   "\u2705 pass",
        "failure":   "\u274c fail",
        "cancelled": "\u23f9 cancelled",
        "skipped":   "\u2b1b skipped",
        "timed_out": "\u23f1 timed out",
        "neutral":   "\U0001f535 neutral",
    }.get(conclusion or "", f"\u2753 {conclusion or 'unknown'}")


def _run_icon(conclusion):
    return {
        "success":   "\u2705 success",
        "failure":   "\u274c failure",
        "cancelled": "\u23f9 cancelled",
    }.get(conclusion or "", f"\u2753 {conclusion or 'unknown'}")


def _fmt_dt(iso):
    if not iso:
        return "unknown"
    try:
        dt = datetime.datetime.fromisoformat(iso.replace("Z", "+00:00"))
        return dt.strftime("%Y-%m-%d %H:%M UTC")
    except Exception:
        return iso


# ---------------------------------------------------------------------------
# Freshness metadata
# ---------------------------------------------------------------------------

def _make_meta(run_number, run_id, run_attempt):
    return (
        f"{_META_PREFIX} run_number={run_number}"
        f" run_id={run_id}"
        f" run_attempt={run_attempt} -->"
    )


def parse_published_meta(text):
    m = re.search(
        r"<!-- CI-STATUS-META:\s*run_number=(\d+)\s+run_id=(\d+)\s+run_attempt=(\d+)",
        text,
    )
    if not m:
        return {}
    return {
        "run_number":  int(m.group(1)),
        "run_id":      int(m.group(2)),
        "run_attempt": int(m.group(3)),
    }


def is_newer(pending, published):
    if not published:
        return True
    if pending["run_number"] > published["run_number"]:
        return True
    if pending["run_number"] == published["run_number"]:
        return pending["run_attempt"] > published["run_attempt"]
    return False


# ---------------------------------------------------------------------------
# Block generator
# ---------------------------------------------------------------------------

def generate_block(run, jobs, repo, *, master_sha=""):
    run_id      = run.get("id", 0)
    run_number  = run.get("run_number", 0)
    run_attempt = run.get("run_attempt", 1)
    run_url     = run.get("html_url", f"https://github.com/{repo}/actions")
    head_sha    = run.get("head_sha", "")
    head_branch = run.get("head_branch", "master")
    conclusion  = run.get("conclusion")
    updated_at  = run.get("updated_at") or run.get("created_at", "")
    short_sha   = head_sha[:7] if head_sha else "unknown"
    commit_url  = f"https://github.com/{repo}/commit/{head_sha}" if head_sha else "#"

    is_stale = bool(master_sha and head_sha and master_sha != head_sha)

    lines = []

    lines.append(_make_meta(run_number, run_id, run_attempt))
    lines.append(_GEN_COMMENT)
    lines.append(
        f"<!-- Run #{run_number} attempt {run_attempt}"
        f" | SHA {short_sha} | {_fmt_dt(updated_at)} -->"
    )
    lines.append("")

    if is_stale:
        lines.append(
            f"> \u26a0\ufe0f **STALE** \u2014 run #{run_number}"
            f" tested commit `{short_sha}`, not current master HEAD `{master_sha[:7]}`."
            " This status does not reflect the current revision."
        )
        lines.append("")

    lines.append(
        f"### {_run_icon(conclusion)}"
        f" [CI Run #{run_number} \u2014 attempt {run_attempt}]({run_url})"
    )
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    lines.append(
        f"| **Tested commit** | [`{short_sha}`]({commit_url}) on `{head_branch}`"
        " *(CI-tested commit; distinct from the README-update commit)* |"
    )
    lines.append(f"| **Completed** | {_fmt_dt(updated_at)} |")
    lines.append(f"| **Workflow** | [{WORKFLOW_NAME}]({run_url}) |")
    lines.append("")

    if conclusion not in ("success",):
        lines.append(
            f"> \u274c **CI run did not succeed** (conclusion: `{conclusion or 'unknown'}`)."
            f" Review the [run logs]({run_url}) for details."
        )
        lines.append("")

    # All jobs that have a name are included — never filter by step presence.
    # A skipped job may have 0 steps (matrix skipped before substitution) but
    # must still appear in the table.  Unresolved template variables in the name
    # (e.g. "${{ matrix.nic }}") are displayed verbatim as-is.
    valid_jobs = [j for j in jobs if j.get("name")]
    if valid_jobs:
        lines.append(
            f"<details><summary>Job results ({len(valid_jobs)} jobs)</summary>"
        )
        lines.append("")
        lines.append("| Job | Result |")
        lines.append("|---|---|")
        for job in valid_jobs:
            name    = job["name"].replace("|", "\\|")
            icon    = _conclusion_icon(job.get("conclusion"))
            job_url = job.get("html_url", "")
            if job_url:
                lines.append(f"| [{name}]({job_url}) | {icon} |")
            else:
                lines.append(f"| {name} | {icon} |")
        lines.append("")
        lines.append("</details>")
    else:
        lines.append("> \u2b1b No job data available for this run.")

    lines.append("")
    lines.append("#### Detailed Reports")
    lines.append("")
    lines.append(
        f"| Report | Link |"
    )
    lines.append("|---|---|")
    lines.append(
        f"| Full run logs and downloadable artefacts"
        f" | [CI run #{run_number}]({run_url}) |"
    )
    lines.append(
        f"| JUnit test results (from this run)"
        f" | [test-reporter check runs]({run_url}) \u2014 open the run, then"
        f" view the Checks tab or Tests tab |"
    )
    lines.append(
        f"| Traceability matrices (from this run)"
        f" | [traceability-unit-\\* and traceability-integration-\\* artefacts]({run_url})"
        f" \u2014 listed under Artefacts on the run page |"
    )
    lines.append(
        f"| Standards compliance report (from this run)"
        f" | [compliance-report artefact]({run_url}) |"
    )
    # Committed historical evidence — static links, not from the current run
    history_xml_url = (
        f"https://github.com/{repo}/blob/master/test-evidence/hardware-results-latest.xml"
    )
    history_trace_url = (
        f"https://github.com/{repo}/blob/master/test-evidence/traceability-summary-latest.md"
    )
    lines.append(
        f"| HIL hardware results (committed historical, not this run)"
        f" | [hardware-results-latest.xml]({history_xml_url}) |"
    )
    lines.append(
        f"| Traceability summary (committed historical, not this run)"
        f" | [traceability-summary-latest.md]({history_trace_url}) |"
    )
    lines.append("")
    lines.append("> **Scope of this status block:**")
    lines.append(
        "> CI execution results from GitHub Actions job metadata only."
        " The following are **not** synthesised here from job conclusions:"
    )
    lines.append("> - Individual test pass/fail/skip counts")
    lines.append("> - Driver build configuration or artefact identity")
    lines.append("> - Hardware adapter coverage or NIC availability")
    lines.append("> - Loaded-driver identity or driver provenance")
    lines.append(">")
    lines.append(
        "> **Artefact integrity note:** The `Hardware Test Evidence` CI job"
        " publishes the committed `test-evidence/` directory via dorny/test-reporter."
        " That directory contains **historical** HIL results committed on a prior date"
        " and does **not** reflect this run's hardware execution."
        " Fresh HIL logs (when available) are in the `hil-mandatory-logs-*` artefact."
    )
    lines.append(">")
    lines.append(
        "> **Known JUnit data issue:** The committed `hardware-results-latest.xml`"
        " reports `failures=17` in the root attribute but contains only 15"
        " `<failure>` child elements. Two suites (`test_extended_diag`,"
        " `test_ioctl_abi`) set `failures=1` in their `testsuite` attribute"
        " while generating a `<skipped/>` child — an over-count in the XML converter."
        " Do not use the root attribute count as the authoritative failure figure."
    )

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# README writer with freshness guard
# ---------------------------------------------------------------------------

def update_readme(readme_path, new_block, pending_meta):
    with open(readme_path, encoding="utf-8") as f:
        content = f.read()

    start_idx = content.find(START_MARKER)
    end_idx   = content.find(END_MARKER)

    if start_idx == -1 or end_idx == -1:
        print(f"ERROR: CI-STATUS markers not found in {readme_path}", file=sys.stderr)
        return "error"
    if start_idx >= end_idx:
        print("ERROR: START marker appears after END marker", file=sys.stderr)
        return "error"

    current_block  = content[start_idx + len(START_MARKER) : end_idx]
    published_meta = parse_published_meta(current_block)

    if not is_newer(pending_meta, published_meta):
        pub_n = published_meta.get("run_number", "?")
        pub_a = published_meta.get("run_attempt", "?")
        pen_n = pending_meta["run_number"]
        pen_a = pending_meta["run_attempt"]
        print(
            f"SKIP: pending #{pen_n}(attempt {pen_a}) is not newer than"
            f" published #{pub_n}(attempt {pub_a}) \u2014 no update written.",
            file=sys.stderr,
        )
        return "skipped_stale"

    new_content = (
        content[: start_idx + len(START_MARKER)]
        + "\n"
        + new_block
        + "\n"
        + content[end_idx:]
    )

    if new_content == content:
        return "skipped_stale"

    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(new_content)
    return "updated"


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Generate README CI-STATUS block from a completed CI run."
    )
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--run-id", type=int, default=None)
    parser.add_argument("--readme", default="README.md")
    parser.add_argument("--repo", default=None)
    args = parser.parse_args()

    repo       = args.repo or os.environ.get("GITHUB_REPOSITORY", "zarfld/IntelAvbFilter")
    token      = os.environ.get("GITHUB_TOKEN", "")
    run_id_env = args.run_id or int(os.environ.get("CI_RUN_ID", "0") or "0") or None
    master_sha = os.environ.get("MASTER_SHA", "")

    if not token:
        print("ERROR: GITHUB_TOKEN is required.", file=sys.stderr)
        sys.exit(1)

    if run_id_env:
        print(f"Fetching run {run_id_env} from {repo}...")
        run = get_run(token, repo, run_id_env)
    else:
        print(f"Discovering latest completed '{WORKFLOW_NAME}' run on master...")
        run = get_latest_run(token, repo)

    if not run:
        print("ERROR: Could not retrieve CI run metadata.", file=sys.stderr)
        sys.exit(1)

    print(
        f"Run #{run.get('run_number')} attempt {run.get('run_attempt', 1)}"
        f" (ID {run.get('id')}): conclusion={run.get('conclusion')}"
        f" sha={run.get('head_sha', '')[:7]}"
    )

    try:
        jobs = get_jobs(token, repo, run["id"], run.get("run_attempt", 1))
    except RuntimeError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(1)
    print(f"Retrieved {len(jobs)} jobs")

    block = generate_block(run, jobs, repo, master_sha=master_sha)

    if args.dry_run:
        print(f"\n{START_MARKER}")
        print(block)
        print(f"{END_MARKER}")
        return

    pending_meta = {
        "run_number":  run.get("run_number", 0),
        "run_id":      run.get("id", 0),
        "run_attempt": run.get("run_attempt", 1),
    }
    result = update_readme(args.readme, block, pending_meta)
    if result == "updated":
        print(f"README.md updated (run #{pending_meta['run_number']})")
    elif result == "skipped_stale":
        print("README.md not changed (idempotent or newer run already published)")
    else:
        sys.exit(1)


if __name__ == "__main__":
    main()
